#!/usr/bin/env node
/*
 * Generate js/token-index.js — the list of bestiary art that has NO
 * token-cropped counterpart.
 *
 * WHY THIS EXISTS
 * ---------------
 * Monster portraits prefer 5etools' cropped head-shot, whose path is derived
 * from the full-art path by inserting "tokens/":
 *     bestiary/MM/Goblin.webp  ->  bestiary/tokens/MM/Goblin.webp
 * That derivation is a guess, and for 262 of the 2,580 renderable monsters
 * (10%) the token simply doesn't exist — so every one of them fired a 404
 * before falling back to the full art.
 *
 * The obvious fix — trust the `hasToken` flag in the bestiary data — does not
 * work: it is set to true on all 4,454 monster entries, including all 262
 * that have no token file. It carries no information. Measured, not assumed.
 *
 * So we precompute the exceptions. Listing the MISSES (262 entries, ~7 KB)
 * rather than the hits (2,318, ~60 KB) keeps the payload small.
 *
 * STALENESS IS SAFE: if art is added later without regenerating, the new
 * monster 404s once and renderIcon()'s onerror fallback still recovers it —
 * the index is an optimization, not a correctness dependency.
 *
 * Run after changing the art pack:  node tools/make-token-index.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data', 'bestiary');
const TOKENS = path.join(ROOT, 'img', 'bestiary', 'tokens');
const OUT = path.join(ROOT, 'js', 'token-index.js');

function readJson(f) {
  try { return JSON.parse(fs.readFileSync(f, 'utf8')); }
  catch (e) { console.warn('[tokens] unreadable', path.basename(f), e.message); return null; }
}

// Mirror the app's own selection rule (js/data-loader.js): the portrait is the
// first image that isn't a battle map.
function firstArt(entry) {
  const imgs = (entry && entry.images) || [];
  for (const im of imgs) {
    const p = im && im.href && im.href.path;
    if (p && im.imageType !== 'map' && im.imageType !== 'mapPlayer') return p;
  }
  return null;
}

function main() {
  if (!fs.existsSync(TOKENS)) {
    console.error('[tokens] ' + TOKENS + ' not found — the art pack must be on disk to regenerate.');
    process.exit(1);
  }
  const files = fs.readdirSync(DATA).filter(f => /^fluff-bestiary-.*\.json$/i.test(f));

  // Directory listings, read once per source. Case-sensitive compare: the CDN
  // is case-sensitive even though Windows' filesystem is not, so a case-only
  // mismatch is a real 404 in production and must count as a miss here.
  const listing = new Map();
  const has = (src, file) => {
    if (!listing.has(src)) {
      let names = [];
      try { names = fs.readdirSync(path.join(TOKENS, src)); } catch (e) {}
      listing.set(src, new Set(names));
    }
    return listing.get(src).has(file);
  };

  const misses = new Set();
  let checked = 0;
  for (const f of files) {
    const json = readJson(path.join(DATA, f));
    if (!json) continue;
    for (const entry of (json.monsterFluff || [])) {
      const art = firstArt(entry);
      // Only bestiary/<SRC>/<file> paths are token-derivable.
      const m = art && /^bestiary\/([^/]+)\/(.+)$/.exec(art);
      if (!m) continue;
      checked++;
      if (!has(m[1], m[2])) misses.add(m[1] + '/' + m[2]);
    }
  }

  const list = [...misses].sort();
  const body = '// GENERATED by tools/make-token-index.js — do not hand-edit.\n'
    + '// Bestiary art with no token-cropped version. See that script for why\n'
    + '// this is precomputed instead of read from the data\'s hasToken flag.\n'
    + '// Keys are "<SOURCE>/<file>" — the shared tail of both the art path\n'
    + '// (bestiary/<key>) and the token path (bestiary/tokens/<key>).\n'
    + 'window.TOKEN_MISSES = new Set([\n'
    + list.map(s => '  ' + JSON.stringify(s) + ',').join('\n')
    + '\n]);\n';

  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (prev === body) {
    console.log('[tokens] ' + list.length + ' misses of ' + checked + ' · unchanged');
    return;
  }
  fs.writeFileSync(OUT, body);
  console.log('[tokens] ' + list.length + ' misses of ' + checked + ' art paths · wrote js/token-index.js');
  console.log('[tokens] remember to re-run tools/stamp-build.js');
}

main();
